/** 角色外形与人设说明，直接喂给分镜文档 */
function castBrief(who) {
  const c = CAST[who];
  if (!c) return '';
  return c.name + '（' + c.species + '）：' + c.look + '；配色 ' + c.color +
    '；性格缺陷——' + c.flaw + '；口头禅——' + c.catch.map(s => '「' + s + '」').join('、') +
    '；成长弧光——' + c.growth + '；声音——' + c.voice;
}
function of(id) { return LINES[id] || null; }
/** 某一页属于八步中的哪一步 */
function arcOf(id, scene) {
  const L = of(id);
  if (!L || !L.arc) return null;
  const key = L.arc[scene];
  return key ? { id: key, name: ARC_NAME[key], step: ARC_IDS.indexOf(key) + 1 } : null;
}
/** 某一页的因果触发点 */
function chainOf(id, scene) {
  const L = of(id);
  return (L && L.chain && L.chain[scene]) || null;
}

module.exports = { ARC, ARC_IDS, ARC_NAME, CAST, KID_VIEW, KID_VIEW_IDS, LINES, castBrief, of, arcOf, chainOf };
